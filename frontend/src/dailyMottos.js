function poolFor(grade) {
  const g = Number(grade) || 0
  if (g <= 2) return G12
  if (g <= 4) return G12.concat(MID)
  return MID.concat(HIGH)
}

export function mottoFor(date, salt = '', grade = 0) {
  const pool = poolFor(grade)
  const day = Math.floor(Date.parse(String(date).slice(0, 10) + 'T00:00:00') / 86400000) || 0
  let extra = 0
  for (let i = 0; i < salt.length; i++) extra = (extra * 31 + salt.charCodeAt(i)) >>> 0
  return pool[(day + extra) % pool.length]
}
