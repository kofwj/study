function pad(n) {
  return String(n).padStart(2, '0')
}

function localIso() {
  const n = new Date()
  return `${n.getFullYear()}-${pad(n.getMonth() + 1)}-${pad(n.getDate())}`
}

function toIso(date) {
  const s = String(date || '')
  const iso = s.match(/^(\d{4})-(\d{2})-(\d{2})/)
  if (iso) return iso[0]
  const cn = s.match(/(\d{4})年(\d{1,2})月(\d{1,2})日/)
  if (cn) return `${cn[1]}-${pad(cn[2])}-${pad(cn[3])}`
  return localIso()
}

function poolFor(grade) {
  const g = Number(grade) || 0
  if (g <= 2) return G12
  if (g <= 4) return G12.concat(MID)
  return MID.concat(HIGH)
}

