export function tagHelp(tag) {
  const name = tag?.name || tag?.tag_name || ''
  const subject = tag?.subject_id || ''
  if (EXACT[name]) return EXACT[name]
  if (name.includes('拼读')) return '先读字母组合的发音，再拼读课本单词；读不准或拼不出来就选这一项。'
  if (name.startsWith('用实验')) return '让孩子按课本完成实验，说出看到的现象和结论；只背结论不算会。'
  if (name.startsWith('比较')) return '让孩子完成一次比较，说清“比什么、结果是什么、为什么”。'
  if (name.startsWith('解释')) return '让孩子画图、举例或用自己的话解释；只复述词语不算会。'
  if (name.startsWith('设计')) return '让孩子写出要解决的问题、模仿什么和怎么做，再画一张简单草图。'
  if (name.startsWith('说清') || name.startsWith('讲清')) return '让孩子不看书讲给你听；时间、人物、事件或理由说不完整就选这一项。'
  if (name.startsWith('用史实') || name.startsWith('用事实') || name.startsWith('用数据')) return '让孩子至少举两条课文里的事实或数据，再说这些事实说明什么。'
  if (name.startsWith('按时间线')) return '让孩子按先后顺序列出事件，再讲清每一步发生了什么。'
  if (name.startsWith('列举')) return '让孩子从课本找出至少三项例子，并说明每项属于什么方面。'
  if (name.startsWith('说出')) return '让孩子结合课本或自己的生活说出具体内容，不能只说“知道了”。'
  if (name.includes('小数乘法')) return '让孩子算两题，并说清积的小数点为什么放在那里。'
  if (name.includes('小数除法')) return '让孩子算两题，并说清商的小数点为什么放在那里。'
  if (name.includes('可能性')) return '给一个具体情况，让孩子判断并说出“一定、可能或不可能”的理由。'
  if (subject === '数学') return '让孩子独立做两道同类题，再说出每一步为什么这么做；答案或步骤错就选这一项。'
  if (subject === '科学') return '按课本完成对应实验或观察，说出“看到了什么、说明什么”；只会背结论不算会。'
  if (subject === '道法') return '合上书讲给你听：发生了什么、为什么重要、能举什么课文例子；讲不完整就选这一项。'
  if (subject === '英语') return '让孩子用本单元词汇和句型说或写三句；发音、句型或回答不对就选这一项。'
  if (subject === '语文') return '让孩子不看书完成相关表达，再说清依据；读不懂、说不清或写不出就选这一项。'
  return '让孩子先完成本单元下面的相关任务；需要提醒、做错或说不清时，就选这一项。'
}
